// ホスト（ターミナル環境）に依存する操作をまとめたポート。
//
// ここに書けるのは「ホストに何をしてほしいか」だけで、**特定のホストの語彙を入れてはいけない**
// （docs/architecture.md「ホスト依存の操作は1つのポートにまとめる」）。実装は src/server/host/adapter/orca-host.ts。
//
// **失敗を例外にしない。** ホストのコマンドが無い環境ではその操作を諦めて動作を続けるのが
// 要件（docs/display.md 4.2「フォールバック」）なので、成否を戻り値で返す。
//
// **操作は「ビューを見せる」と「ファイルを開く」の2つだけ。** 画面も入力もブラウザのページ側で
// 完結するので、ホストに頼るのは「そのページをどこかに出す」と「レポートに書かれたファイルを
// ホストのエディタで開く」に絞ってある。箱を替えるときに差し替えるのもここ1つ
// （docs/research/app-shell.md）。

/** ホストへの依頼の結果。失敗しても呼び出し側は続行できる。 */
export type HostResult = { readonly ok: true } | { readonly ok: false; readonly reason: string }

export type Host = {
  /**
   * URL のビューを見えている状態にする。まだ無ければ開き、既にあればその内容を最新にする。
   * 開くのと更新するのを1つにしてあるのは、呼び出し側が「今どちらの状態か」を持たずに
   * 済ませるため（同じ URL で何度呼んでもビューは1つ）。
   */
  readonly showView: (url: string) => Promise<HostResult>
  /**
   * ファイルを1つ、ホストのエディタで開く（`docs/display.md` 4.2「各表示物」。
   * レポートに書かれたパスを押したとき）。**`path` は cwd 相対**で、渡す前にそれが
   * git 管理下にあるかどうかを確かめるのは呼び出し側（`./tracked-file.ts`）——ここは
   * 「開いてほしい」を渡すだけで、任意の文字列を通してよいかどうかは判断しない。
   * **行番号は渡さない**（いまのホストに口が無い）。
   */
  readonly openFile: (path: string) => Promise<HostResult>
}
