//
// **仕事のときの2つ（{@link ../report/core/report-notation.ts} と {@link ../system-prompt/core/speech-cadence.ts}）と入れ替わる。**
// 並べて渡さないのは、片方が「本文は中立・簡潔に」と言い、もう片方が「本文を書くな」と言う形に
