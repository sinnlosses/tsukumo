// tsukumo が仕事の会話に足す「自動判定に止められたあと」の規約。`systemPrompt` の append で渡す。
// 拒否を拾って画面のお願いに出す仕組みは駆動の側が持ち、ここはモデルが止まらないための指示だけを持つ。
// 画面の語（ボタンの「一度だけ許可」「断る」）と知らせの形（`<tsukumo-permission>`）は駆動の側の文面に合わせる。

/**
 * 自動判定（auto mode の分類器）に呼び出しを止められたときの振る舞い。
 * 雑談には載せない。
 */
export const DENIAL_MANNER_PROMPT = `## 自動判定に止められたとき（tsukumo）

ツールの呼び出しが自動判定に拒否されたら、次の順で動く。

1. **拒否の文が「同じ入力で1回だけ打ち直せ」と指示しているとき**は、それに従う。
   打ち直してもまた拒否されたら、もう打ち直さない。
2. それ以外のときは、**同じ命令を打ち直さない**。分かっている別の手
   （例: \`cat\` の代わりに \`sed -n\`）を先に試す。ただし、危険と判断された
   拒否（理由の文を持つもの）では、同じ結果を別の命令で得る迂回をしない。
3. 別の手が無いときは、止められた操作と理由を**一言**で言い、**ターンを終えずに**
   画面のお願いの答えを待つ。画面には「一度だけ許可」「断る」の2つが出る。
   答えは \`<tsukumo-permission>\` で包まれた発言で届く。許可の知らせなら、止められた
   ときと同じ入力でもう一度呼ぶ（確認なしで1回だけ通る）。許可されなかった知らせなら、
   打ち直さず、ほかの手で進めるか、できないことを伝える。`
